/// Iceblade Hacker and Warblade of Caer Darrow: melee attacks with this weapon deal Frost
/// damage, only on the hand holding it, like every generated weapon proc.
fn melee_frost_proc(env: &mut Environment, name: &str, item_id: i32, spell_id: i32, damage: f64) {
    let trigger_dpm: TriggerDpmFn =
        Rc::new(move |sim, unit| dynamic_legacy_proc_for_weapon(sim, unit, item_id, 0.0, 1.0));
    apply_proc_damage_effect(
        env,
        &ProcDamageEffect {
            item_id,
            spell_id,
            school: school::FROST,
            defense_type: DefenseType::Melee,
            min_dmg: damage,
            max_dmg: damage,
            flags: SpellFlag::NO_ON_CAST_COMPLETE
                | SpellFlag::PASSIVE_SPELL
                | SpellFlag::NO_ON_DAMAGE_DEALT
                | SpellFlag::PROC
                | SpellFlag::SUPPRESS_WEAPON_PROCS,
            trigger: ProcTrigger {
                name: name.to_string(),
                action_id: ActionId::item(item_id),
                callback: CallbackMask::ON_SPELL_HIT_DEALT,
                proc_mask: ProcMask::MELEE,
                outcome: HitOutcome::LANDED,
                require_damage_dealt: true,
                proc_chance: 1.0,
                ..ProcTrigger::default()
            },
            trigger_dpm: Some(trigger_dpm),
            ..ProcDamageEffect::default()
        },
    );
}

