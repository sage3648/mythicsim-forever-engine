/// A use spell on the item's own cooldown and the shared category (2554) Second Wind and Burst
/// of Knowledge sit in.
fn mana_item_spell(env: &mut Environment, item_id: i32, cooldown: i64) -> super::sim::SpellId {
    let unit = env.player;
    let timer = env.sim.new_timer(unit);
    let category = env.sim.category_timer(unit, 2554);
    env.sim.register_spell(
        unit,
        SpellConfig {
            action_id: ActionId::item(item_id),
            proc_mask: ProcMask::EMPTY,
            flags: SpellFlag::NO_ON_CAST_COMPLETE,
            cast: CastConfig {
                cd: Cooldown {
                    timer: Some(timer),
                    duration: cooldown,
                },
                shared_cd: Cooldown {
                    timer: Some(category),
                    duration: 10 * SECOND,
                },
                ..CastConfig::default()
            },
            ..SpellConfig::default()
        },
    )
}

fn add_mana_cooldown(env: &mut Environment, spell: super::sim::SpellId) {
    let unit = env.player;
    env.sim.add_major_cooldown(
        unit,
        MajorCooldown {
            spell,
            priority: 0,
            cooldown_type: cooldown_type::MANA,
            allow_spell_queueing: false,
            timings: Vec::new(),
        },
    );
}

/// Second Wind: use: restores 63 mana every 1 sec for 10 sec (15604). 15 min cooldown, and 10 sec
/// on the category it shares with Burst of Knowledge.
fn second_wind(env: &mut Environment) {
    if !env.sim.has_mana_bar(env.player) {
        return;
    }
    let spell = mana_item_spell(env, 11819, 15 * 60 * SECOND);
    add_mana_cooldown(env, spell);
}

/// Burst of Knowledge: use: reduces the mana cost of all spells by 150 for 10 sec (15646). The
/// client's school mask (126) leaves out Physical.
fn burst_of_knowledge(env: &mut Environment) {
    let unit = env.player;
    if !env.sim.has_mana_bar(unit) {
        return;
    }
    let aura = env.sim.register_aura(
        unit,
        AuraConfig {
            label: "Burst of Knowledge".to_string(),
            action_id: Some(ActionId::item(11832)),
            duration: 10 * SECOND,
            ..AuraConfig::default()
        },
    );
    env.sim.attach_spell_mod(
        aura,
        SpellModConfig {
            kind: SpellModType::PowerCostFlat,
            school: 126,
            resource_type: Some(Resource::Mana),
            int_value: -150,
            ..SpellModConfig::default()
        },
    );
    let spell = mana_item_spell(env, 11832, 6 * 60 * SECOND);
    add_mana_cooldown(env, spell);
}

