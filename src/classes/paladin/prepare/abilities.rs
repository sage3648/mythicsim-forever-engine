    /// Go `registerHammerOfWrath`: hurls a hammer that strikes an enemy for 498 Holy damage.
    /// Only usable on enemies that have 20% or less health.
    pub(super) fn register_hammer_of_wrath(&mut self, sim: &mut Sim, unit: UnitId, rank: &Row) {
        let damage = rank.damage_effect();
        let timer = shared_timer(sim, unit, &mut self.timers.hammer_of_wrath);

        sim.register_spell(
            unit,
            SpellConfig {
                action_id: spell_action(rank.id),
                spell_school: rank.spell_school(),
                defense_type: rank.defense_type_core(),
                proc_mask: ProcMask::RANGED_SPECIAL,
                flags: SpellFlag::APL,
                class_spell_mask: masks::HAMMER_OF_WRATH,
                rank: rank.rank_number(),
                max_range: f64::from(rank.max_range),
                missile_speed: f64::from(rank.speed),
                cost: mana_cost(rank),
                cast: CastConfig {
                    // The client's 1s GCD sits at core's floor, so it is named as the floor
                    // too or GCDTime clamps it.
                    default_cast: Cast {
                        gcd_min: rank.gcd(),
                        gcd: rank.gcd(),
                        cast_time: rank.cast_time(),
                        ..Cast::default()
                    },
                    cd: crate::prepare::sim::Cooldown {
                        timer: Some(timer),
                        duration: cooldown(rank),
                    },
                    ..CastConfig::default()
                },
                damage_multiplier: 1.0,
                threat_multiplier: 1.0,
                bonus_coefficient: damage.coeff(),
                has_extra_cast_condition: true,
                ..SpellConfig::default()
            },
        );
    }

