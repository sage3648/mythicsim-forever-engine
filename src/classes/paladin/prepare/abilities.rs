    /// Go `registerConsecration`: consecrates the land beneath the Paladin, doing X Holy
    /// damage over 8 sec to enemies who enter the area.
    pub(super) fn register_consecration(
        &mut self,
        sim: &mut Sim,
        unit: UnitId,
        n: i32,
        rank: &Row,
    ) {
        let tick_spell = spell_data().consecration_triggered.rank(n);
        let tick = tick_spell.effect_n(1);

        let dummy = rank.effect(dbcenums::A_PERIODIC_DUMMY, 0);
        let tick_length = dummy.period();
        let number_of_ticks = (rank.duration() / tick_length) as i32;

        let timer = shared_timer(sim, unit, &mut self.timers.consecration);
        let label = sim.unit(unit).label.clone();
        sim.register_spell(
            unit,
            SpellConfig {
                action_id: spell_action(rank.id),
                spell_school: rank.spell_school(),
                defense_type: rank.defense_type_core(),
                proc_mask: ProcMask::SPELL_DAMAGE,
                flags: SpellFlag::APL,
                class_spell_mask: masks::CONSECRATION,
                rank: rank.rank_number(),
                damage_multiplier: 1.0,
                threat_multiplier: 1.0,
                max_range: 8.0,
                cost: mana_cost(rank),
                cast: gcd_cast(rank.gcd(), 0, Some((timer, cooldown(rank)))),
                dot: DotConfig {
                    is_aoe: true,
                    aura: AuraConfig {
                        action_id: Some(spell_action(rank.id)),
                        label: format!("Consecration{label} Rank {}", rank.rank_number()),
                        ..AuraConfig::default()
                    },
                    // The client ticks on a 1 sec period with no tick-on-apply attribute, so
                    // the first tick lands 1 sec in, as on master.
                    number_of_ticks,
                    tick_length,
                    bonus_coefficient: tick.coeff(),
                    ..DotConfig::default()
                },
                ..SpellConfig::default()
            },
        );
    }

