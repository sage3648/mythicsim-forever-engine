#[cfg(test)]
mod tests {
    use super::*;
    use crate::prepare::item_test_support::{aura, environment, spell};
    use crate::prepare::sim::NEVER_EXPIRES;

    #[test]
    fn every_item_is_one_go_registers() {
        let tables = crate::data::tables::tables();
        for item in ITEMS {
            assert!(
                tables.item_effect_ids.contains(&item),
                "item {item} is not registered by Go"
            );
        }
    }

    #[test]
    fn a_damage_shield_listens_to_melee_hits_taken_and_casts_its_spell() {
        // Naglering: 3 Arcane damage to the attacker off every melee hit the wearer takes.
        let env = environment(&[(11669, 0)]);
        let id = aura(&env, "Naglering");
        let shield = env.sim.aura(id);
        assert_eq!(shield.action_id_for_proc, Some(ActionId::item(11669)));
        assert_eq!(
            shield.callback_names(),
            vec!["on_reset", "on_spell_hit_taken"]
        );
        let spell = env.sim.spell(spell(&env, &ActionId::spell(15438)));
        assert_eq!(spell.spell_school, school::ARCANE);
        assert_eq!(spell.defense_type, DefenseType::Magic);
        assert!(spell.flags.matches(SpellFlag::BINARY | SpellFlag::PROC));
    }

    #[test]
    fn omokks_girth_restrainer_lowers_threat_by_one_percent() {
        let env = environment(&[(13959, 0)]);
        let id = aura(&env, "Omokk's Girth Restrainer");
        assert!(env.sim.aura(id).active);
        assert_eq!(env.sim.aura(id).duration, NEVER_EXPIRES);
        assert_eq!(
            env.sim.unit(env.player).pseudo_stats.threat_multiplier,
            0.99
        );
    }

    #[test]
    fn an_iceblade_rolls_only_on_the_hand_that_holds_it() {
        // Iceblade Hacker: a fixed chance of 1 on the main hand it is wielded in.
        let env = environment(&[(13952, 0)]);
        let trigger = env.sim.aura(aura(&env, "Iceblade Hacker"));
        let dpm = trigger.dpm.as_ref().expect("a proc manager");
        assert_eq!(dpm.proc_masks, vec![ProcMask::MELEE_MH]);
        assert_eq!(dpm.proc_chances, vec![1.0]);
    }

    #[test]
    fn the_lion_horn_buffs_armor_from_the_item_effect() {
        let env = environment(&[(14557, 0)]);
        let trigger = env.sim.aura(aura(&env, "The Lion Horn of Stormwind"));
        assert_eq!(
            trigger.callback_names(),
            vec!["on_reset", "on_spell_hit_taken"]
        );
        let buff = env.sim.aura(aura(&env, "The Lion Horn of Stormwind Proc"));
        assert_eq!(buff.duration, 30 * SECOND);
        assert_eq!(buff.icd, trigger.icd);
    }
}
